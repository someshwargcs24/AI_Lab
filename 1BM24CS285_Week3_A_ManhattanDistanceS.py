import heapq

GOAL = (1, 2, 3, 4, 5, 6, 7, 8, 0)

def h2_manhattan(state):
    distance = 0
    for i in range(9):
        val = state[i]
        if val != 0:
            target_idx = val - 1
            r1, c1 = i // 3, i % 3
            r2, c2 = target_idx // 3, target_idx % 3
            distance += abs(r1 - r2) + abs(c1 - c2)
    return distance

def get_neighbors(state):
    neighbors = []
    zero_idx = state.index(0)
    row, col = zero_idx // 3, zero_idx % 3
    moves = [(-1, 0), (1, 0), (0, -1), (0, 1)]

    for dr, dc in moves:
        nr, nc = row + dr, col + dc
        if 0 <= nr < 3 and 0 <= nc < 3:
            new_idx = nr * 3 + nc
            board = list(state)
            board[zero_idx], board[new_idx] = board[new_idx], board[zero_idx]
            neighbors.append(tuple(board))
    return neighbors

def a_star_manhattan(initial_state):
    open_set = []
    heapq.heappush(open_set, (h2_manhattan(initial_state), 0, initial_state, [initial_state]))
    visited = set()

    while open_set:
        f, g, current, path = heapq.heappop(open_set)

        if current == GOAL:
            return path

        if current in visited:
            continue
        visited.add(current)

        for neighbor in get_neighbors(current):
            if neighbor not in visited:
                new_g = g + 1
                new_f = new_g + h2_manhattan(neighbor)
                heapq.heappush(open_set, (new_f, new_g, neighbor, path + [neighbor]))
    return None

def print_board(state):
    for i in range(0, 9, 3):
        print(" ".join("." if x == 0 else str(x) for x in state[i:i+3]))
    print()

start_state = (1, 2, 3, 4, 0, 6, 7, 5, 8)
path = a_star_manhattan(start_state)

for step, state in enumerate(path):
    print(f"Step {step}:")
    print_board(state)